/// Material icon names, as the Flutter SDK knows them, to SF Symbols.
///
/// The keys are exactly the names of `_materialIconMap` in
/// sdk/lib/src/builders/builder_helpers.dart (156 entries, aliases such as
/// `cart` and `profile` included); a test reads that map and fails when a
/// name is missing here. Each symbol is the nearest SF Symbol available on
/// iOS 16, filled where the Material icon is filled and outlined where it is
