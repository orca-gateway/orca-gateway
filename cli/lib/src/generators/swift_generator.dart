import '../manifest/plugin_schema.dart';

/// Generates a Swift plugin stub from a [PluginSchema], against the iOS SDK's
/// `OrcaPlugin` protocol (sdk-swift/Sources/OrcaGateway/OrcaPlugin.swift).
///
/// Per widget a props type reading the resolved node's props and its trigger
/// names; per action a params type reading the raw action object; and the
/// plugin type with a placeholder builder and a no-op handler for each. The
/// output depends only on [pluginName] and the schema, so it is reproducible.
class SwiftGenerator {
  SwiftGenerator._();

  /// Generate a complete Swift file for [pluginName]. A null or empty
  /// [schema] gives a plugin with only its name.
  static String generate(String pluginName, PluginSchema? schema) {
    final widgets = schema?.widgets ?? const <String, WidgetSchema>{};
    final actions = schema?.actions ?? const <String, ActionSchema>{};
    final buf = StringBuffer();

    buf.writeln('// Generated by `orca plugin generate --lang swift` from '
        '$pluginName/orca_plugin.yaml.');
    buf.writeln('// Edit the widget builders and action handlers below: '
        'they are placeholders.');
    buf.writeln('#if canImport(SwiftUI)');
    buf.writeln('import OrcaGateway');
    buf.writeln('import SwiftUI');
    buf.writeln();

    for (final entry in widgets.entries) {
      _emitProps(buf, entry.key, entry.value);
    }
    for (final entry in actions.entries) {
      _emitParams(buf, entry.key, entry.value);
    }
    _emitPlugin(buf, pluginName, widgets, actions);

    buf.writeln('#endif');
    return buf.toString();
  }

  // ── Widget props ──────────────────────────────────────

  static void _emitProps(StringBuffer buf, String name, WidgetSchema widget) {
    buf.writeln('/// The props of a `$name` node, read from its resolved props.');
    buf.writeln('public struct ${name}Props {');
    buf.writeln('    public let node: ResolvedNode');
    buf.writeln();
    buf.writeln('    public init(_ node: ResolvedNode) {');
    buf.writeln('        self.node = node');
    buf.writeln('    }');
    if (widget.props.isNotEmpty) buf.writeln();
    for (final entry in widget.props.entries) {
      _emitEnumDoc(buf, entry.value);
      final read = 'node["${entry.key}"]';
      buf.writeln('    public var ${entry.key}: ${_type(entry.value)}? '
          '{ $read${_accessor(entry.value, optional: true)} }');
    }
    if (widget.triggers.isNotEmpty) {
      buf.writeln();
      buf.writeln('    /// The triggers a `$name` fires, for '
          '`model.fire(_:on:eventData:)`.');
      buf.writeln('    public enum Triggers {');
      for (final trigger in widget.triggers) {
        buf.writeln('        public static let $trigger = "$trigger"');
      }
      buf.writeln('    }');
    }
    buf.writeln('}');
    buf.writeln();
  }

  // ── Action params ─────────────────────────────────────

  static void _emitParams(StringBuffer buf, String type, ActionSchema action) {
    final pascal = _toPascalCase(type);
    buf.writeln('/// The params of a `$type` action, read from the raw action '
        'object (values as sent, unresolved).');
    buf.writeln('public struct ${pascal}Params {');
    buf.writeln('    public let action: JSONValue');
    buf.writeln();
    buf.writeln('    public init(_ action: JSONValue) {');
    buf.writeln('        self.action = action');
    buf.writeln('    }');
    if (action.params.isNotEmpty) buf.writeln();
    for (final entry in action.params.entries) {
      _emitEnumDoc(buf, entry.value);
      final read = 'action["${entry.key}"]';
      final accessor = _accessor(entry.value, optional: false);
      final body = accessor.isEmpty ? '$read.isNull ? nil : $read' : '$read$accessor';
      buf.writeln(
          '    public var ${entry.key}: ${_type(entry.value)}? { $body }');
    }
    buf.writeln('}');
    buf.writeln();
  }

  // ── Plugin ────────────────────────────────────────────

  static void _emitPlugin(StringBuffer buf, String pluginName,
      Map<String, WidgetSchema> widgets, Map<String, ActionSchema> actions) {
    final typeName = '${_toPascalCase(pluginName)}Plugin';
    buf.writeln('/// The $pluginName plugin: register it with the host.');
    buf.writeln('public struct $typeName: OrcaPlugin {');
    buf.writeln('    public let name = "$pluginName"');
    buf.writeln();
    buf.writeln('    public init() {}');

    if (widgets.isNotEmpty) {
      buf.writeln();
      buf.writeln('    public var widgets: [String: OrcaWidgetBuilder] {');
      buf.writeln('        [');
      for (final name in widgets.keys) {
        buf.writeln('            // TODO: draw the $name from ${name}Props(node), '
            'firing its triggers with model.fire(_:on:eventData:).');
        buf.writeln('            "$name": { _, _ in AnyView(Text("$name")) },');
      }
      buf.writeln('        ]');
      buf.writeln('    }');
    }

    if (actions.isNotEmpty) {
      buf.writeln();
      buf.writeln('    public var actions: [String: OrcaActionHandler] {');
      buf.writeln('        [');
      for (final type in actions.keys) {
        final params = '${_toPascalCase(type)}Params';
        buf.writeln('            // TODO: run $type with its $params.');
        buf.writeln('            "$type": { action, _ in _ = $params(action) },');
      }
      buf.writeln('        ]');
      buf.writeln('    }');
    }

    final withTriggers =
        widgets.entries.where((e) => e.value.triggers.isNotEmpty).toList();
    if (withTriggers.isNotEmpty) {
      buf.writeln();
      buf.writeln('    public var triggers: [String: [TriggerDefinition]] {');
      buf.writeln('        [');
      for (final entry in withTriggers) {
        buf.writeln('            "${entry.key}": [');
        for (final trigger in entry.value.triggers) {
          buf.writeln('                TriggerDefinition(name: '
              '${entry.key}Props.Triggers.$trigger),');
        }
        buf.writeln('            ],');
      }
      buf.writeln('        ]');
      buf.writeln('    }');
    }

    buf.writeln('}');
  }

  // ── Type Resolution Helpers ───────────────────────────

  static void _emitEnumDoc(StringBuffer buf, PropSchema prop) {
    if (prop.type == 'string' &&
        prop.enumValues != null &&
        prop.enumValues!.isNotEmpty) {
      buf.writeln('    /// One of: ${prop.enumValues!.join(', ')}.');
    }
  }

  /// The Swift type of a prop: string, number and boolean map to String,
  /// Double and Bool; anything else stays the SDK's JSONValue.
  static String _type(PropSchema prop) {
    return switch (prop.type) {
      'string' => 'String',
      'number' => 'Double',
      'boolean' => 'Bool',
      _ => 'JSONValue',
    };
  }

  /// The JSONValue accessor reading a prop as its [_type], empty for
  /// JSONValue. [optional] chains it after an optional value.
  static String _accessor(PropSchema prop, {required bool optional}) {
    final chain = optional ? '?.' : '.';
    return switch (prop.type) {
      'string' => '${chain}stringValue',
      'number' => '${chain}doubleValue',
      'boolean' => '${chain}boolValue',
      _ => '',
    };
  }

  /// `orca_google_map` → `OrcaGoogleMap`, `moveCamera` → `MoveCamera`.
  static String _toPascalCase(String name) {
    return name
        .split(RegExp('[_-]'))
        .where((part) => part.isNotEmpty)
        .map((part) => '${part[0].toUpperCase()}${part.substring(1)}')
        .join();
  }
}
