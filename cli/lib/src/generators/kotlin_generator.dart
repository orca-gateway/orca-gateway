import '../manifest/plugin_schema.dart';

/// Generates a Kotlin plugin stub from a [PluginSchema], against the Android
/// SDK's `OrcaPlugin` interface
/// (sdk-kotlin/sdk/src/main/kotlin/com/orcagateway/sdk/OrcaPlugin.kt).
///
/// Per widget a props type reading the resolved node's props and its trigger
/// names; per action a params type reading the raw action object; and the
/// plugin type with a placeholder builder and a no-op handler for each. The
/// output depends only on its inputs, so it is reproducible.
class KotlinGenerator {
  KotlinGenerator._();

  /// Generate a complete Kotlin file for [pluginName] in [packageName]. A
  /// null or empty [schema] gives a plugin with only its name.
  static String generate(String pluginName, PluginSchema? schema,
      {String packageName = 'orca.plugins'}) {
    final widgets = schema?.widgets ?? const <String, WidgetSchema>{};
    final actions = schema?.actions ?? const <String, ActionSchema>{};
    final hasTriggers = widgets.values.any((w) => w.triggers.isNotEmpty);
    final buf = StringBuffer();

    buf.writeln('package $packageName');
    buf.writeln();
    buf.writeln('// Generated by `orca plugin generate --lang kotlin` from '
        '$pluginName/orca_plugin.yaml.');
    buf.writeln('// Edit the widget builders and action handlers below: '
        'they are placeholders.');
    buf.writeln();

    final imports = <String>{'com.orcagateway.sdk.OrcaPlugin'};
    if (widgets.isNotEmpty) {
      imports.addAll([
        'androidx.compose.foundation.text.BasicText',
        'com.orcagateway.core.render.ResolvedNode',
        'com.orcagateway.sdk.WidgetBuilder',
      ]);
    }
    if (widgets.values.any((w) => w.props.values.any(_isJson))) {
      imports.add('com.orcagateway.core.json.JsonValue');
    }
    if (actions.isNotEmpty) {
      imports.addAll([
        'com.orcagateway.core.plugins.OrcaActionHandler',
        'kotlinx.serialization.json.JsonObject',
      ]);
    }
    if (actions.values.any((a) => a.params.isNotEmpty)) {
      imports.add('com.orcagateway.core.json.JsonValue');
    }
    if (hasTriggers) imports.add('com.orcagateway.core.plugins.TriggerDefinition');
    for (final import in imports.toList()..sort()) {
      buf.writeln('import $import');
    }
    buf.writeln();

    for (final entry in widgets.entries) {
      _emitProps(buf, entry.key, entry.value);
    }
    for (final entry in actions.entries) {
      _emitParams(buf, entry.key, entry.value);
    }
    _emitPlugin(buf, pluginName, widgets, actions, hasTriggers);

    return buf.toString();
  }

  // ── Widget props ──────────────────────────────────────

  static void _emitProps(StringBuffer buf, String name, WidgetSchema widget) {
    buf.writeln('/** The props of a `$name` node, read from its resolved props. */');
    buf.writeln('public class ${name}Props(public val node: ResolvedNode) {');
    for (final entry in widget.props.entries) {
      _emitEnumDoc(buf, entry.value);
      buf.writeln('    public val ${entry.key}: ${_type(entry.value)}? get() = '
          'node["${entry.key}"]${_accessor(entry.value)}');
    }
    if (widget.triggers.isNotEmpty) {
      if (widget.props.isNotEmpty) buf.writeln();
      buf.writeln('    /** The triggers a `$name` fires, for '
          '`model.fire(trigger, on = node, eventData = ...)`. */');
      buf.writeln('    public object Triggers {');
      for (final trigger in widget.triggers) {
        buf.writeln('        public const val $trigger: String = "$trigger"');
      }
      buf.writeln('    }');
    }
    buf.writeln('}');
    buf.writeln();
  }

  // ── Action params ─────────────────────────────────────

  static void _emitParams(StringBuffer buf, String type, ActionSchema action) {
    final pascal = _toPascalCase(type);
    buf.writeln('/** The params of a `$type` action, read from the raw action '
        'object (values as sent, unresolved). */');
    buf.writeln('public class ${pascal}Params(public val action: JsonObject) {');
    for (final entry in action.params.entries) {
      _emitEnumDoc(buf, entry.value);
      buf.writeln('    public val ${entry.key}: ${_type(entry.value)}? get() = '
          'value("${entry.key}")${_accessor(entry.value)}');
    }
    if (action.params.isNotEmpty) {
      buf.writeln();
      buf.writeln('    private fun value(key: String): JsonValue? =');
      buf.writeln('        action[key]?.let { JsonValue.fromJsonElement(it) }'
          '?.takeUnless { it.isNull }');
    }
    buf.writeln('}');
    buf.writeln();
  }

  // ── Plugin ────────────────────────────────────────────

  static void _emitPlugin(
      StringBuffer buf,
      String pluginName,
      Map<String, WidgetSchema> widgets,
      Map<String, ActionSchema> actions,
      bool hasTriggers) {
    final typeName = '${_toPascalCase(pluginName)}Plugin';
    buf.writeln('/** The $pluginName plugin: register it with the host. */');
    buf.writeln('public class $typeName : OrcaPlugin {');
    buf.writeln('    override val name: String = "$pluginName"');

    if (widgets.isNotEmpty) {
      for (final name in widgets.keys) {
        buf.writeln();
        buf.writeln('    // TODO: draw the $name from ${name}Props(node), '
            'firing its triggers with model.fire(...).');
        buf.writeln('    private val ${_builderName(name)}: WidgetBuilder = '
            '{ _, _, modifier -> BasicText("$name", modifier) }');
      }
      buf.writeln();
      buf.writeln('    override val widgets: Map<String, WidgetBuilder> = mapOf(');
      for (final name in widgets.keys) {
        buf.writeln('        "$name" to ${_builderName(name)},');
      }
      buf.writeln('    )');
    }

    if (actions.isNotEmpty) {
      buf.writeln();
      buf.writeln(
          '    override val actions: Map<String, OrcaActionHandler> = mapOf(');
      for (final type in actions.keys) {
        final params = '${_toPascalCase(type)}Params';
        buf.writeln('        // TODO: run $type with its $params.');
        buf.writeln('        "$type" to OrcaActionHandler { action, _ -> '
            '$params(action) },');
      }
      buf.writeln('    )');
    }

    if (hasTriggers) {
      buf.writeln();
      buf.writeln('    override val triggers: Map<String, '
          'List<TriggerDefinition>> = mapOf(');
      for (final entry in widgets.entries) {
        if (entry.value.triggers.isEmpty) continue;
        buf.writeln('        "${entry.key}" to listOf(');
        for (final trigger in entry.value.triggers) {
          buf.writeln('            TriggerDefinition('
              '${entry.key}Props.Triggers.$trigger),');
        }
        buf.writeln('        ),');
      }
      buf.writeln('    )');
    }

    buf.writeln('}');
  }

  // ── Type Resolution Helpers ───────────────────────────

  static void _emitEnumDoc(StringBuffer buf, PropSchema prop) {
    if (prop.type == 'string' &&
        prop.enumValues != null &&
        prop.enumValues!.isNotEmpty) {
      buf.writeln('    /** One of: ${prop.enumValues!.join(', ')}. */');
    }
  }

  static bool _isJson(PropSchema prop) => _accessor(prop).isEmpty;

  /// The Kotlin type of a prop: string, number and boolean map to String,
  /// Double and Boolean; anything else stays the SDK's JsonValue.
  static String _type(PropSchema prop) {
    return switch (prop.type) {
      'string' => 'String',
      'number' => 'Double',
      'boolean' => 'Boolean',
      _ => 'JsonValue',
    };
  }

  /// The JsonValue accessor reading a prop as its [_type], empty for
  /// JsonValue.
  static String _accessor(PropSchema prop) {
    return switch (prop.type) {
      'string' => '?.stringValue',
      'number' => '?.doubleValue',
      'boolean' => '?.boolValue',
      _ => '',
    };
  }

  /// `GoogleMap` → `googleMapBuilder`.
  static String _builderName(String widget) =>
      '${widget[0].toLowerCase()}${widget.substring(1)}Builder';

  /// `orca_google_map` → `OrcaGoogleMap`, `moveCamera` → `MoveCamera`.
  static String _toPascalCase(String name) {
    return name
        .split(RegExp('[_-]'))
        .where((part) => part.isNotEmpty)
        .map((part) => '${part[0].toUpperCase()}${part.substring(1)}')
        .join();
  }
}
