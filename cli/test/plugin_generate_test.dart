// C16.6 (CLI part): `orca plugin generate` gains `--lang ts|swift|kotlin`,
// `--manifest <orca_plugin.yaml>` and `--package <name>` (Kotlin). The
// TypeScript output stays what TypeScriptGenerator writes today; Swift and
// Kotlin get a plugin stub from the same schema. Whether those stubs compile
// is checked where the SDKs build them (sdk-swift and sdk-kotlin tests).

import 'dart:convert';
import 'dart:io';

import 'package:args/command_runner.dart';
import 'package:orca_gateway_cli/src/commands/plugin_generate.dart';
import 'package:orca_gateway_cli/src/generators/typescript_generator.dart';
import 'package:orca_gateway_cli/src/manifest/plugin_manifest.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

/// The repo's plugins directory (tests run from cli/).
final _plugins = p.normalize(p.absolute('..', 'plugins'));
final _googleMap = p.join(_plugins, 'orca_google_map', 'orca_plugin.yaml');

/// A manifest with no `schema:` section, written by the test that needs one.
const _noSchema = '''
name: orca_voice_recorder
display_name: Voice Recorder
description: Audio recording with amplitude monitoring, pause/resume, and playback.
''';

void main() {
  late Directory tempDir;

  setUp(() {
    tempDir = Directory.systemTemp.createTempSync('orca_cli_generate_');
  });

  tearDown(() {
    tempDir.deleteSync(recursive: true);
  });

  /// Runs `orca plugin generate <args>` with [tempDir] as the project root.
  Future<void> generate(List<String> args) async {
    final runner = CommandRunner<void>('orca', 'test')
      ..addCommand(PluginGenerateCommand(root: tempDir.path));
    await runner.run(['generate', ...args]);
  }

  String output(String fileName) =>
      File(p.join(tempDir.path, 'generated', fileName)).readAsStringSync();

  String todaysTypeScript() => TypeScriptGenerator.generate(
      'orca_google_map', PluginManifest.fromYamlFile(_googleMap).schema!);

  test('C16.6 default --lang ts from pubspec.yaml writes today\'s output',
      () async {
    File(p.join(tempDir.path, 'pubspec.yaml')).writeAsStringSync('''
name: host
dependencies:
  orca_google_map: any
''');
    Directory(p.join(tempDir.path, '.dart_tool')).createSync();
    File(p.join(tempDir.path, '.dart_tool', 'package_config.json'))
        .writeAsStringSync(jsonEncode({
      'configVersion': 2,
      'packages': [
        {
          'name': 'orca_google_map',
          'rootUri': Uri.directory(p.join(_plugins, 'orca_google_map'))
              .toString(),
        },
      ],
    }));

    await generate([]);

    expect(output('orca_google_map.ts'), todaysTypeScript());
  });

  test('C16.6 --lang ts --manifest writes today\'s output as <name>.ts',
      () async {
    await generate(['--lang', 'ts', '--manifest', _googleMap]);

    expect(output('orca_google_map.ts'), todaysTypeScript());
  });

  test('C16.6 --lang swift writes the plugin, props, triggers and params',
      () async {
    await generate(['--lang', 'swift', '--manifest', _googleMap]);
    final swift = output('OrcaGoogleMapPlugin.swift');

    expect(swift, startsWith('// Generated by `orca plugin generate'));
    expect(swift, contains('orca_google_map/orca_plugin.yaml'));
    expect(swift, contains('#if canImport(SwiftUI)\n'));
    expect(swift, endsWith('#endif\n'));
    expect(swift, contains('import OrcaGateway\n'));

    // The plugin type.
    expect(swift, contains('public struct OrcaGoogleMapPlugin: OrcaPlugin {'));
    expect(swift, contains('public init() {}'));
    expect(swift, contains('public let name = "orca_google_map"'));
    expect(swift, contains('public var widgets: [String: OrcaWidgetBuilder]'));
    expect(swift, contains('"GoogleMap": { _, _ in'));
    expect(swift, contains('public var actions: [String: OrcaActionHandler]'));
    expect(swift, contains('_ = MoveCameraParams(action)'));
    expect(swift,
        contains('public var triggers: [String: [TriggerDefinition]]'));

    // The GoogleMap props, typed and optional.
    expect(swift, contains('public struct GoogleMapProps {'));
    expect(swift,
        contains('public var latitude: Double? { node["latitude"]?.doubleValue }'));
    expect(swift,
        contains('public var zoom: Double? { node["zoom"]?.doubleValue }'));
    expect(swift,
        contains('public var mapType: String? { node["mapType"]?.stringValue }'));
    expect(swift, contains('/// One of: normal, satellite, terrain, hybrid.'));
    expect(swift,
        contains('public var myLocationEnabled: Bool? { node["myLocationEnabled"]?.boolValue }'));
    expect(swift,
        contains('public var markers: JSONValue? { node["markers"] }'));

    // The four triggers, as constants and as definitions.
    for (final trigger in ['onTap', 'onLongPress', 'onCameraMove', 'onMarkerTap']) {
      expect(swift, contains('public static let $trigger = "$trigger"'));
      expect(swift,
          contains('TriggerDefinition(name: GoogleMapProps.Triggers.$trigger)'));
    }

    // The moveCamera params, read from the raw action.
    expect(swift, contains('public struct MoveCameraParams {'));
    expect(swift,
        contains('public var targetId: String? { action["targetId"].stringValue }'));
    expect(swift,
        contains('public var latitude: Double? { action["latitude"].doubleValue }'));
    expect(swift,
        contains('public var zoom: Double? { action["zoom"].doubleValue }'));
  });

  test('C16.6 --lang kotlin writes the plugin, props, triggers and params',
      () async {
    await generate(['--lang', 'kotlin', '--manifest', _googleMap]);
    final kotlin = output('OrcaGoogleMapPlugin.kt');

    expect(kotlin, startsWith('package orca.plugins\n'));
    expect(kotlin, contains('// Generated by `orca plugin generate'));
    expect(kotlin, contains('orca_google_map/orca_plugin.yaml'));

    // The plugin type.
    expect(kotlin, contains('public class OrcaGoogleMapPlugin : OrcaPlugin {'));
    expect(kotlin, contains('override val name: String = "orca_google_map"'));
    expect(kotlin, contains('override val widgets: Map<String, WidgetBuilder>'));
    expect(kotlin, contains('"GoogleMap" to googleMapBuilder'));
    expect(kotlin,
        contains('override val actions: Map<String, OrcaActionHandler>'));
    expect(kotlin,
        contains('"moveCamera" to OrcaActionHandler { action, _ -> MoveCameraParams(action) }'));
    expect(kotlin,
        contains('override val triggers: Map<String, List<TriggerDefinition>>'));

    // The GoogleMap props, typed and optional.
    expect(kotlin,
        contains('public class GoogleMapProps(public val node: ResolvedNode) {'));
    expect(kotlin,
        contains('public val latitude: Double? get() = node["latitude"]?.doubleValue'));
    expect(kotlin,
        contains('public val mapType: String? get() = node["mapType"]?.stringValue'));
    expect(kotlin, contains('/** One of: normal, satellite, terrain, hybrid. */'));
    expect(kotlin,
        contains('public val myLocationEnabled: Boolean? get() = node["myLocationEnabled"]?.boolValue'));
    expect(kotlin,
        contains('public val markers: JsonValue? get() = node["markers"]'));

    // The four triggers, as constants and as definitions.
    for (final trigger in ['onTap', 'onLongPress', 'onCameraMove', 'onMarkerTap']) {
      expect(kotlin, contains('public const val $trigger: String = "$trigger"'));
      expect(kotlin,
          contains('TriggerDefinition(GoogleMapProps.Triggers.$trigger)'));
    }

    // The moveCamera params, read from the raw action.
    expect(kotlin,
        contains('public class MoveCameraParams(public val action: JsonObject) {'));
    expect(kotlin,
        contains('public val targetId: String? get() = value("targetId")?.stringValue'));
    expect(kotlin,
        contains('public val zoom: Double? get() = value("zoom")?.doubleValue'));
  });

  test('C16.6 --package sets the Kotlin package', () async {
    await generate([
      '--lang', 'kotlin', '--manifest', _googleMap, //
      '--package', 'com.example.maps',
    ]);

    expect(output('OrcaGoogleMapPlugin.kt'),
        startsWith('package com.example.maps\n'));
  });

  test('C16.6 a manifest without schema gives a plugin with only its name',
      () async {
    final manifest = p.join(tempDir.path, 'orca_plugin.yaml');
    File(manifest).writeAsStringSync(_noSchema);

    await generate(['--lang', 'swift', '--manifest', manifest]);
    await generate(['--lang', 'kotlin', '--manifest', manifest]);
    final swift = output('OrcaVoiceRecorderPlugin.swift');
    final kotlin = output('OrcaVoiceRecorderPlugin.kt');

    expect(swift, contains('public struct OrcaVoiceRecorderPlugin: OrcaPlugin {'));
    expect(swift, contains('public let name = "orca_voice_recorder"'));
    expect(kotlin,
        contains('public class OrcaVoiceRecorderPlugin : OrcaPlugin {'));
    expect(kotlin, contains('override val name: String = "orca_voice_recorder"'));
    for (final member in ['widgets', 'actions', 'triggers']) {
      expect(swift, isNot(contains('var $member')));
      expect(kotlin, isNot(contains('val $member')));
    }
  });

  test('C16.6 --manifest works in a directory with no pubspec.yaml', () async {
    expect(File(p.join(tempDir.path, 'pubspec.yaml')).existsSync(), isFalse);

    await generate(['--lang', 'swift', '--manifest', _googleMap]);
    final first = output('OrcaGoogleMapPlugin.swift');
    await generate(['--lang', 'swift', '--manifest', _googleMap]);

    expect(first, isNotEmpty);
    expect(output('OrcaGoogleMapPlugin.swift'), first, reason: 'deterministic');
  });

  test('C16.6 an unknown --lang is a usage error', () async {
    await expectLater(
      generate(['--lang', 'rust', '--manifest', _googleMap]),
      throwsA(isA<UsageException>()),
    );
    expect(Directory(p.join(tempDir.path, 'generated')).existsSync(), isFalse);
  });
}
