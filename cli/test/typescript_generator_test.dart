// C17.3/ts: a plain string action param is typed `Value | string`, in the
// action interface and in the helper's parameter list, as numbers and booleans
// are `Value | number` / `Value | boolean`. Flutter's plugins resolve string
// params as values (`executor.resolveString`), so a page can pass
// `V.pageState("voicePath")` where a string goes. Enum strings stay their
// literal union, widget props stay `Valueable<T>`, and the helper returns the
// params as given (the JSON is the same).

import 'package:orca_gateway_cli/src/generators/typescript_generator.dart';
import 'package:orca_gateway_cli/src/manifest/plugin_manifest.dart';
import 'package:orca_gateway_cli/src/manifest/plugin_schema.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';
import 'package:yaml/yaml.dart';

/// The voice recorder's manifest (tests run from cli/).
final _voiceRecorder = p.normalize(
    p.absolute('..', 'plugins', 'orca_voice_recorder', 'orca_plugin.yaml'));

/// One action with a string param, a required string param, an enum param and
/// a number param.
const _sampleSchema = '''
actions:
  loadClip:
    params:
      label: { type: string }
      clipId: { type: string, required: true }
      scope: { type: string, enum: [page, app] }
      volume: { type: number }
''';

const _sampleOutput = '''
// Auto-generated by orca plugin generate — DO NOT EDIT
// Source: orca_sample_kit/orca_plugin.yaml

import type { CustomAction, Value } from "orcagateway/types";

// ── Actions ────────────────────────────────────

export interface LoadClipAction extends CustomAction {
  type: "loadClip";
  label?: Value | string;
  clipId: Value | string;
  scope?: "page" | "app";
  volume?: Value | number;
}

export function LoadClip(clipId: Value | string, label?: Value | string, scope?: "page" | "app", volume?: Value | number): LoadClipAction {
  return { type: "loadClip", label, clipId, scope, volume };
}

''';

void main() {
  test('C17.3/ts string action params are Value | string in the interface and '
      'the helper; enum stays its union, number Value | number', () {
    final schema =
        PluginSchema.fromYaml(loadYaml(_sampleSchema) as YamlMap);
    final ts = TypeScriptGenerator.generate('orca_sample_kit', schema);
    expect(ts, _sampleOutput);
  });

  test('C17.3/ts the voice recorder\'s PlayRecording takes path: '
      'Value | string', () {
    final ts = TypeScriptGenerator.generate('orca_voice_recorder',
        PluginManifest.fromYamlFile(_voiceRecorder).schema!);

    expect(ts, contains('import type { ActionMap, CustomAction, Value, '
        'Valueable } from "orcagateway/types";\n'));
    expect(
        ts,
        contains('export interface PlayRecordingAction extends CustomAction {\n'
            '  type: "playRecording";\n'
            '  path: Value | string;\n'
            '  positionKey?: Value | string;\n'
            '  durationKey?: Value | string;\n'
            '  stateKey?: Value | string;\n'
            '  scope?: "page" | "app";\n'
            '}\n'));
    expect(
        ts,
        contains('export function PlayRecording(path: Value | string, '
            'positionKey?: Value | string, durationKey?: Value | string, '
            'stateKey?: Value | string, scope?: "page" | "app"): '
            'PlayRecordingAction {\n'
            '  return { type: "playRecording", path, positionKey, durationKey, '
            'stateKey, scope };\n'
            '}\n'));
    expect(ts, contains('export function SeekPlayback(position?: '
        'Value | number): SeekPlaybackAction {\n'));
    // Widget props stay Valueable<T>.
    expect(ts, contains('  recorderId?: Valueable<string>;\n'));
    expect(ts, isNot(contains(': string;')));
    expect(ts, isNot(contains(': string,')));
    expect(ts, isNot(contains(': string)')));
  });
}
