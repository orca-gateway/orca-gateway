final _committed = p.normalize(p.absolute('..', 'sdk-swift', 'Tests',
    'OrcaGatewayTests', 'Generated', 'OrcaGoogleMapPlugin.swift'));

const _regenerate = 'Regenerate it from cli/: dart run bin/orca.dart plugin '
    'generate --lang swift --manifest ../plugins/orca_google_map/orca_plugin.yaml '
    '--output ../sdk-swift/Tests/OrcaGatewayTests/Generated';

/// A manifest with every shape the generator handles: a widget with string,
/// enum, number, boolean and JSON props and triggers, one with triggers only,
/// one with props only, an action with params of each kind and one with none.
const _sampleManifest = '''
name: orca_sample_kit
schema:
  widgets:
    SampleView:
      kind: primitive
      props:
        label: { type: string, required: true }
        mode: { type: string, enum: [compact, full] }
        level: { type: number }
        enabled: { type: boolean }
        items: { type: array, items: { type: string } }
      triggers: [onPick, onClear]
    SampleBadge:
      kind: primitive
      triggers: [onTap]
    SampleSpacer:
      kind: primitive
      props:
        size: { type: number }
  actions:
    resetSample:
      params:
        sampleId: { type: string, required: true }
        delay: { type: number }
        force: { type: boolean }
        mode: { type: string, enum: [soft, hard] }
        extra: { type: object }
