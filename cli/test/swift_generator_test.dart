// C16.6 (Swift drift): the google_map Swift stub committed in the SwiftUI
// test target (sdk-swift/Tests/OrcaGatewayTests/Generated), which the Swift
// suite compiles and exercises, is exactly what `orca plugin generate --lang
// swift` writes for plugins/orca_google_map/orca_plugin.yaml today.
//
// C17.5/gen (Swift): `--types-only` writes `<Pascal>Types.swift`, the props,
// params and trigger-name types alone (what a shipped plugin package compiles:
// no plugin stub, no placeholder, no SwiftUI). Without the flag the stub stays
// byte for byte what the generator wrote before the flag existed.

import 'dart:io';

