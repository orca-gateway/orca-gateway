void main() {
  late Directory tempDir;

  setUp(() {
    tempDir = Directory.systemTemp.createTempSync('orca_cli_kotlin_');
  });

  tearDown(() {
    tempDir.deleteSync(recursive: true);
  });

  test('C16.6 the committed Kotlin google_map stub is the generator output '
      'byte for byte', () async {
    final runner = CommandRunner<void>('orca', 'test')
      ..addCommand(PluginGenerateCommand(root: tempDir.path));
    await runner
        .run(['generate', '--lang', 'kotlin', '--manifest', _googleMap]);
    final generated =
        File(p.join(tempDir.path, 'generated', 'OrcaGoogleMapPlugin.kt'))
            .readAsStringSync();

    // Strict UTF-8 on both sides, so equal strings are equal bytes; a string
    // mismatch prints a readable diff.
    final committed = File(_committed);
    expect(committed.existsSync(), isTrue,
        reason: 'No stub at $_committed. $_regenerate');
    expect(committed.readAsStringSync(), generated,
        reason: 'The committed stub drifted from the generator. $_regenerate');
  });

  /// Runs `orca plugin generate --lang kotlin --package com.example.samples
  /// --manifest <yaml> [extra]` on [yaml] written to the temp dir, and lists
  /// the files it generated.
  Future<List<String>> generate(String yaml, [List<String> extra = const []]) async {
    final manifest = File(p.join(tempDir.path, 'orca_plugin.yaml'))
      ..writeAsStringSync(yaml);
    final runner = CommandRunner<void>('orca', 'test')
      ..addCommand(PluginGenerateCommand(root: tempDir.path));
    await runner.run([
      'generate', '--lang', 'kotlin', '--package', 'com.example.samples', //
      '--manifest', manifest.path, ...extra,
    ]);
    final out = Directory(p.join(tempDir.path, 'generated'));
    if (!out.existsSync()) return [];
    return [for (final f in out.listSync()) p.basename(f.path)]..sort();
  }

  String output(String fileName) =>
      File(p.join(tempDir.path, 'generated', fileName)).readAsStringSync();

  test('C17.5/gen kotlin without --types-only writes the stub as before, '
      'byte for byte', () async {
    expect(await generate(_sampleManifest), ['OrcaSampleKitPlugin.kt']);
    expect(output('OrcaSampleKitPlugin.kt'), _sampleStub);
  });

  test('C17.5/gen kotlin --types-only writes <Pascal>Types.kt: the stub\'s '
      'props, params and triggers alone', () async {
    expect(await generate(_sampleManifest, ['--types-only']),
        ['OrcaSampleKitTypes.kt']);
    final types = output('OrcaSampleKitTypes.kt');

    // The same types as the stub, everything before the plugin type, with
    // only the imports they use.
    final body = _sampleStub
        .substring(_sampleStub.indexOf('/** The props of a'),
            _sampleStub.indexOf('/** The orca_sample_kit plugin'))
        .trimRight();
    expect(
        types,
        'package com.example.samples\n'
        '\n'
        '// Generated by `orca plugin generate --lang kotlin --types-only` '
        'from orca_sample_kit/orca_plugin.yaml.\n'
        '// Do not edit: rerun the command after changing the manifest.\n'
        '\n'
        'import com.orcagateway.core.json.JsonValue\n'
        'import com.orcagateway.core.render.ResolvedNode\n'
        'import kotlinx.serialization.json.JsonObject\n'
        '\n'
        '$body\n');
    for (final stubOnly in [
      'OrcaPlugin', 'OrcaSampleKitPlugin', 'compose', 'WidgetBuilder', //
      'OrcaActionHandler', 'TriggerDefinition', 'TODO', 'placeholder',
    ]) {
      expect(types, isNot(contains(stubOnly)));
    }
  });

  test('C17.5/gen kotlin --types-only on a manifest without schema writes '
      'nothing', () async {
    expect(await generate('name: orca_bare\n', ['--types-only']), isEmpty);
  });
}
