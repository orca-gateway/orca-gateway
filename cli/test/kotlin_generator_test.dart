// C16.6 (Kotlin drift): the google_map Kotlin stub committed in the Android
// SDK's test source set (sdk-kotlin/sdk/src/test/kotlin/orca/plugins), which
// the Gradle build compiles and GeneratedPluginTest exercises, is exactly what
// `orca plugin generate --lang kotlin` writes for
// plugins/orca_google_map/orca_plugin.yaml today (default package
// orca.plugins).
//
// C17.5/gen (Kotlin): `--types-only` writes `<Pascal>Types.kt`, the props,
// params and trigger-name types alone (what a shipped plugin module compiles:
// no plugin stub, no placeholder, no Compose). Without the flag the stub stays
// byte for byte what the generator wrote before the flag existed.

import 'dart:io';

import 'package:args/command_runner.dart';
import 'package:orca_gateway_cli/src/commands/plugin_generate.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

/// Paths from the cli package root (tests run from cli/).
final _googleMap = p.normalize(
    p.absolute('..', 'plugins', 'orca_google_map', 'orca_plugin.yaml'));
final _committed = p.normalize(p.absolute('..', 'sdk-kotlin', 'sdk', 'src',
    'test', 'kotlin', 'orca', 'plugins', 'OrcaGoogleMapPlugin.kt'));

const _regenerate = 'Regenerate it from cli/: dart run bin/orca.dart plugin '
    'generate --lang kotlin --manifest ../plugins/orca_google_map/orca_plugin.yaml '
    '--output ../sdk-kotlin/sdk/src/test/kotlin/orca/plugins';

/// A manifest with every shape the generator handles: a widget with string,
/// enum, number, boolean and JSON props and triggers, one with triggers only,
/// one with props only, an action with params of each kind and one with none.
const _sampleManifest = '''
name: orca_sample_kit
schema:
  widgets:
    SampleView:
      kind: primitive
      props:
        label: { type: string, required: true }
        mode: { type: string, enum: [compact, full] }
        level: { type: number }
        enabled: { type: boolean }
        items: { type: array, items: { type: string } }
      triggers: [onPick, onClear]
    SampleBadge:
      kind: primitive
      triggers: [onTap]
    SampleSpacer:
      kind: primitive
      props:
        size: { type: number }
  actions:
    resetSample:
      params:
        sampleId: { type: string, required: true }
        delay: { type: number }
        force: { type: boolean }
        mode: { type: string, enum: [soft, hard] }
        extra: { type: object }
    clearSamples: {}
''';

/// What `--lang kotlin --package com.example.samples` wrote for
/// [_sampleManifest] before `--types-only` existed (captured from the
/// generator at 644d5d8).
const _sampleStub = r'''
